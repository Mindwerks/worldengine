class TestSimplex(unittest.TestCase):
    def test_matches_the_c_noise_library(self):
        for x, y, octaves, base, expected in GOLDEN:
            actual = float(snoise2(x, y, octaves, base=base))
            self.assertAlmostEqual(
                expected,
                actual,
                delta=TOLERANCE,
                msg="snoise2(%r, %r, %d, base=%d): expected %r, got %r" % (x, y, octaves, base, expected, actual),
            )

    def test_array_input_matches_scalar_input(self):
        xs = numpy.linspace(-40.0, 40.0, 97)
        ys = numpy.linspace(-13.0, 71.0, 61).reshape(-1, 1)
        grid = snoise2(xs, ys, 8, base=8199)
        self.assertEqual((61, 97), grid.shape)
        for j in (0, 7, 60):
            for i in (0, 1, 55, 96):
                self.assertAlmostEqual(float(snoise2(xs[i], ys[j, 0], 8, base=8199)), float(grid[j, i]), delta=1e-9)

    def test_output_is_bounded(self):
        xs = numpy.linspace(-500.0, 500.0, 991)
        values = snoise2(xs, xs.reshape(-1, 1), 8, base=17)
        self.assertTrue(numpy.isfinite(values).all())
        self.assertLessEqual(numpy.abs(values).max(), 1.0)

    def test_rejects_non_positive_octaves(self):
        for octaves in (0, -1):
            with self.assertRaises(ValueError):
                snoise2(0.5, 0.5, octaves)


